"""Version identity for executable package bytes and the actual installed dependencies."""

import hashlib
from importlib.metadata import distributions
from pathlib import Path

import pycode
from pycode.core.values import json_dumps


def package_manifest():
    package = Path(pycode.__file__).resolve().parent
    records = []
    for path in sorted(package.rglob("*")):
        if (
            path.is_file()
            and "__pycache__" not in path.parts
            and "licenses" not in path.relative_to(package).parts
            and path.suffix != ".pyc"
        ):
            records.append(
                {
                    "path": path.relative_to(package).as_posix(),
                    "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                }
            )
    # The coding harness (solver prompt, tool gate, runner) shapes every result too.
    harness = Path(__file__).resolve().parents[1]
    for folder in ("coding", "quality"):
        for path in sorted((harness / folder).rglob("*.py")):
            records.append(
                {
                    "path": path.relative_to(harness.parent).as_posix(),
                    "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                }
            )
    digest = hashlib.sha256(
        json_dumps(records, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    return {
        "sha256": digest,
        "scope": (
            "runtime pycode package files excluding generated bytecode and licenses,"
            " plus evals/coding and evals/quality harness sources"
        ),
        "files": records,
    }


def installed_dependencies():
    versions = {}
    for distribution in distributions():
        versions[distribution.metadata["Name"]] = distribution.version
    return dict(sorted(versions.items(), key=lambda pair: pair[0].casefold()))
