"""Memory storage, extraction and selection are explicit boundaries."""

from typing import Protocol

from pycode.core.memory import MemoryCandidate, MemoryRecord


class MemoryStore(Protocol):
    async def list_records(self) -> tuple[MemoryRecord, ...]: ...
    async def list_index(self) -> tuple[dict, ...]: ...
    async def read_record(self, memory_id: str) -> MemoryRecord: ...
    async def candidates(self) -> tuple[MemoryCandidate, ...]: ...
    async def save_candidate(self, candidate: MemoryCandidate) -> None: ...
    async def write(self, record: MemoryRecord, *, expected_hash=None) -> None: ...
    async def remove(self, memory_id: str, *, expected_hash=None) -> None: ...
    async def review(self, candidate_id: str, decision: str, timestamp: float) -> None: ...
    async def set_mode(self, mode: str) -> None: ...
    async def get_mode(self) -> str: ...


class MemoryExtractor(Protocol):
    model_id: str

    async def extract(self, snapshot, run_id: str) -> tuple[dict, ...]: ...
