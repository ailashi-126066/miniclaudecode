"""Local team capabilities; no framework or concrete filesystem dependencies."""

from typing import Protocol

from pycode.core.messages import Message
from pycode.core.runtime import RunResult


class ChildSession(Protocol):
    async def run(self, message: Message) -> RunResult: ...
    async def resume(self, answers=None) -> RunResult: ...
    async def cancel(self) -> bool: ...
    async def record_team_parent(self, data: dict) -> None: ...
    async def inspect(self, *, presentation=False) -> dict: ...
    async def aclose(self) -> None: ...


class ChildSessions(Protocol):
    workspace: str

    async def open(self, record, member, *, create, fork_from=None, fork_entry_ids=None): ...
    async def input_accepted(self, recipient, input_id): ...


class Worktrees(Protocol):
    async def create(self, *, base="HEAD", include_uncommitted=False): ...
    async def update(self, record): ...
    async def inspect(self, identifier): ...
    async def changes(self, identifier, limit=20000): ...
    async def merge_preview(self, identifier, review_fingerprint, action="merge"): ...
    async def merge_into_workspace(self, identifier, preview, action="merge"): ...
    async def complete_team_merge(self, identifier, merge_commit): ...
