"""Read-only Skill discovery/content and application activation boundaries."""

from typing import Protocol

from pycode.kernel import ExecutableTool as Tool
from pycode.skills.domain.skills import SkillDocument, SkillEntry, SkillIndex


class SkillCatalog(Protocol):
    async def scan(self) -> SkillIndex: ...
    async def read(self, entry: SkillEntry) -> SkillDocument: ...
    async def resource(self, entry: SkillEntry, relative_path: str) -> str: ...
    async def tools(self, entry: SkillEntry) -> tuple[dict, ...]: ...
    async def verify_resources(self, activation: dict) -> None: ...
    async def entry_at_virtual_path(self, virtual_path: str): ...
    def virtual_path(self, entry: SkillEntry) -> str: ...


class SkillResourceToolFactory(Protocol):
    def create(self, declaration: dict, activation: dict) -> Tool: ...


class SkillCatalogCommands(Protocol):
    async def request(self, name: str, args: str = "") -> dict: ...
    async def search(self, query: str, limit: int = 10) -> tuple[dict, ...]: ...
    async def install(self, url: str, *, ref=None, subpath=None) -> dict: ...


class SkillInstaller(Protocol):
    async def install(self, url: str, *, ref=None, subpath=None) -> dict: ...
