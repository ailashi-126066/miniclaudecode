"""Skills contracts: component-owned implementation."""

from typing import Protocol

from pycode.kernel import SessionSnapshot
from pycode.skills.types import SkillDocument, SkillEntry, SkillIndex


class CatalogWriteGuard(Protocol):
    def can_initialize(self, snapshot: SessionSnapshot) -> bool: ...


class SkillCatalog(Protocol):
    async def write(
        self, name: str, content: str, *, scope="user", expected_revision=None
    ) -> SkillEntry: ...
    async def scan(self) -> SkillIndex: ...
    async def read(self, entry: SkillEntry) -> SkillDocument: ...
    async def resource(self, entry: SkillEntry, relative_path: str) -> str: ...
    async def entry_at_virtual_path(self, virtual_path: str): ...
    def virtual_path(self, entry: SkillEntry) -> str: ...


class SkillCatalogCommands(Protocol):
    async def load(self, name: str, args: str = "") -> dict: ...
    async def search(self, query: str, limit: int = 10) -> tuple[dict, ...]: ...
    async def install(self, url: str, *, ref=None, subpath=None) -> dict: ...
    async def create(self, name: str, content: str, *, scope="user") -> dict: ...
    async def update(
        self, name: str, content: str, *, expected_revision: str, scope="user"
    ) -> dict: ...


class SkillInstaller(Protocol):
    async def install(self, url: str, *, ref=None, subpath=None) -> dict: ...
