"""Presentation depends on public application commands, never mutable execution state."""

from collections.abc import Sequence
from typing import Any, Protocol

from pycode.kernel import Message, RunResult


class ModelChoice(Protocol):
    @property
    def provider(self) -> str: ...
    @property
    def model_id(self) -> str: ...
    @property
    def availability(self) -> str: ...


class ModelChoices(Protocol):
    @property
    def models(self) -> Sequence[ModelChoice]: ...


class SandboxAvailability(Protocol):
    @property
    def reason(self) -> str: ...


class InteractiveSession(Protocol):
    async def name(self, title) -> object: ...
    async def run(self, message: Message) -> RunResult: ...
    async def resume(self, answers: dict | None = None) -> RunResult: ...
    async def cancel(self) -> bool: ...
    async def answer_agent(self, agent_id, answer) -> object: ...
    async def cancel_agent(self, agent_id) -> object: ...
    async def wait_team(self) -> object: ...
    async def wake_team(self) -> RunResult | None: ...
    def team_wake_pending(self) -> bool: ...
    async def inspect(self, *, presentation=False) -> dict: ...
    async def read_tool_result(
        self, output_id, *, offset=1, limit=2000, byte_offset=0
    ) -> object: ...
    async def usage(self, run_id=None) -> dict: ...
    async def publish_result(self, result, *, collect_background=False) -> object: ...
    async def model_list(self, *, refresh=False) -> ModelChoices: ...
    async def select_model(self, provider: str, model_id: str) -> object: ...
    async def branch(self, leaf_id: str | None) -> None: ...
    async def compact(self) -> object: ...
    async def enter_plan(self, task="") -> object: ...
    async def storage_status(self) -> object: ...
    async def storage_gc(self, *, dry_run=False) -> object: ...
    async def memory_list(self) -> dict[str, Any]: ...
    async def memory_mode(self, mode) -> object: ...
    async def memory_remove(self, memory_id, *, scope=None) -> object: ...
    async def memory_edit(self, memory_id, content, *, scope=None) -> object: ...
    async def memory_undo(self) -> dict[str, Any]: ...
    async def memory_clear(self) -> object: ...
    async def memory_extract(self) -> object: ...
    async def load_skill(self, name, args="") -> RunResult: ...
    async def reload_skills(self) -> dict[str, Any]: ...
    async def skill_search(self, query="", limit=10) -> Sequence[dict[str, Any]]: ...
    async def install_skill(self, url, ref=None, subpath=None) -> dict[str, Any]: ...
    async def save_skill(
        self, name, content, *, scope="user", expected_revision=None
    ) -> dict[str, Any]: ...
    async def read_skill(self, name) -> Any: ...
    async def preview_revert(self, target_leaf_id, mode="dialogue") -> object: ...
    async def revert(self, plan) -> object: ...
    async def recover_revert(self, restore_id, *, compensate=False) -> object: ...
    async def submit_input(self, message, kind) -> bool: ...
    async def aclose(self) -> None: ...


class InteractiveSessions(Protocol):
    async def open(self, session_id, *, create, consumer) -> InteractiveSession: ...
    async def list_sessions(self) -> Sequence[dict[str, Any]]: ...
    async def sandbox_status(self) -> SandboxAvailability: ...
    async def fork(self, source_id, leaf_id, target_id) -> dict[str, Any]: ...
