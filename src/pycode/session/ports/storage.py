"""Owned content storage and its auditable quarantine boundary."""

from typing import Protocol

from pycode.session.domain.storage import StorageInventory, StoredObject


class StorageObjects(Protocol):
    async def inventory(self) -> StorageInventory: ...
    async def apply(self, item: StoredObject, action: str, timestamp: float) -> None: ...
    async def audit(self, data: dict) -> None: ...
    async def quarantine_session(self, session_id: str, timestamp: float) -> None: ...
    async def mark_session_deleted(self, session_id: str, timestamp: float) -> None: ...
    async def restore_session(self, session_id: str, timestamp: float) -> None: ...
