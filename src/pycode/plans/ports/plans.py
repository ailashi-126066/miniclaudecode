"""Real replacement boundaries: Plan file storage and current-process questions."""

from typing import Protocol

from pycode.plans.domain.plans import PlanDocument


class PlanFiles(Protocol):
    def configure(self, plan_id: str) -> None: ...
    def deactivate(self) -> None: ...
    def virtual_path(self, plan_id: str) -> str: ...
    def storage_path(self, plan_id: str) -> str: ...
    async def read(self, plan_id: str) -> PlanDocument: ...
    async def exists(self, plan_id: str) -> bool: ...


class QuestionPrompt(Protocol):
    async def ask(self, payload: dict) -> dict: ...
